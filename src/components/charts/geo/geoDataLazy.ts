function makeBoxPolygon(
  minLng: number,
  minLat: number,
  maxLng: number,
  maxLat: number,
  chamfer = 0.18
): [number, number][][] {
  const dx = (maxLng - minLng) * chamfer;
  const dy = (maxLat - minLat) * chamfer;
  return [[
    [minLng + dx, minLat],
    [maxLng - dx, minLat],
    [maxLng, minLat + dy],
    [maxLng, maxLat - dy],
    [maxLng - dx, maxLat],
    [minLng + dx, maxLat],
    [minLng, maxLat - dy],
    [minLng, minLat + dy],
    [minLng + dx, minLat],
  ]];
}

