import { 
  X, 
  Download, 
  ExternalLink, 
  Copy, 
  Check, 
  Terminal, 
  FileCode2, 
  Play, 
  CheckCircle2,
  Sparkles,
  BookOpen
} from 'lucide-react';
import { ColumnProfile, ProjectMetadata } from '../../types';

